#!/usr/bin/env python3
"""Generate a self-contained Kubernetes manifest for Destroyer."""

import argparse
from pathlib import Path
import re
import sys


NAMESPACE_PATTERN = re.compile(r"^[a-z0-9]([-a-z0-9]*[a-z0-9])?$")


def read_destroyer_code() -> str:
    source_path = Path(__file__).with_name("Destroyer.py")
    try:
        return source_path.read_text(encoding="utf-8")
    except OSError as exc:
        raise SystemExit(f"Unable to read {source_path}: {exc}") from exc


def strip_cli_for_inline(code: str) -> str:
    """Remove the command-line entry point before embedding the source."""
    code = code.replace("import argparse\n", "")
    prefix, marker, _ = code.partition("\ndef main(")
    if not marker:
        raise ValueError("Destroyer.py does not contain a main function")

    return prefix.rstrip() + """


print("Starting Destroyer on port 8080")
logging.basicConfig(
    level=logging.INFO if DEBUG else logging.WARNING,
    format="%(asctime)s %(levelname)s %(message)s",
)
if DEBUG:
    print("[DEBUG] Debug logging enabled")
if REDEPLOY_DRY_RUN:
    print("[DRY-RUN] Dry-run mode enabled; pods will not be deleted")
ThreadingHTTPServer(("0.0.0.0", 8080), Handler).serve_forever()
"""


def validate_namespace(namespace: str) -> str:
    if len(namespace) > 63 or not NAMESPACE_PATTERN.fullmatch(namespace):
        raise ValueError(
            "namespace must be a lowercase DNS label of no more than 63 characters"
        )
    return namespace


def generate_yaml(
    namespace: str = "default",
    enable_redeploy: bool = False,
    allowed_namespaces: tuple[str, ...] = (),
) -> str:
    """Return the Kubernetes resources required to run Destroyer."""
    namespace = validate_namespace(namespace)
    allowed_namespaces = tuple(
        validate_namespace(value) for value in allowed_namespaces
    )
    if enable_redeploy and not allowed_namespaces:
        raise ValueError("at least one allowed namespace is required to enable redeploy")
    if allowed_namespaces and not enable_redeploy:
        raise ValueError("allowed namespaces require --enable-redeploy")

    inline_code = strip_cli_for_inline(read_destroyer_code())
    indented_code = "\n".join(
        f"              {line}" if line.strip() else ""
        for line in inline_code.splitlines()
    )
    rbac_resources = ""
    if enable_redeploy:
        rbac_resources = f"""---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: destroyer
rules:
  - apiGroups: [""]
    resources: ["pods"]
    verbs: ["get", "delete"]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRoleBinding
metadata:
  name: destroyer
subjects:
  - kind: ServiceAccount
    name: destroyer
    namespace: {namespace}
roleRef:
  kind: ClusterRole
  name: destroyer
  apiGroup: rbac.authorization.k8s.io
"""

    return f'''# Generated by generate_deployment.py. Review before applying.
---
apiVersion: v1
kind: ServiceAccount
metadata:
  name: destroyer
  namespace: {namespace}
automountServiceAccountToken: {str(enable_redeploy).lower()}
{rbac_resources}---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: destroyer
  namespace: {namespace}
  labels:
    app: destroyer
spec:
  replicas: 1
  selector:
    matchLabels:
      app: destroyer
  template:
    metadata:
      labels:
        app: destroyer
    spec:
      serviceAccountName: destroyer
      automountServiceAccountToken: {str(enable_redeploy).lower()}
      securityContext:
        runAsNonRoot: true
        runAsUser: 65532
        runAsGroup: 65532
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: destroyer
          image: python:3.12.16-slim-trixie
          imagePullPolicy: IfNotPresent
          command: [python3, "-u", "-c"]
          args:
            - |
{indented_code}
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities:
              drop: [ALL]
          env:
            - name: PYTHONDONTWRITEBYTECODE
              value: "1"
            - name: PYTHONUNBUFFERED
              value: "1"
            - name: POD_NAME
              valueFrom:
                fieldRef:
                  fieldPath: metadata.name
            - name: POD_NAMESPACE
              valueFrom:
                fieldRef:
                  fieldPath: metadata.namespace
            - name: ALERT_WEBHOOK_URL
              valueFrom:
                secretKeyRef:
                  name: destroyer-webhooks
                  key: ALERT_WEBHOOK_URL
                  optional: true
            - name: TEAMS_WEBHOOK_URL
              valueFrom:
                secretKeyRef:
                  name: destroyer-webhooks
                  key: TEAMS_WEBHOOK_URL
                  optional: true
            - name: WEBHOOK_TOKEN
              valueFrom:
                secretKeyRef:
                  name: destroyer-webhooks
                  key: WEBHOOK_TOKEN
                  optional: true
            - name: ENABLE_POD_REDEPLOY
              value: "{str(enable_redeploy).lower()}"
            - name: REDEPLOY_MIN_AGE_SECONDS
              value: "15"
            - name: REDEPLOY_DRY_RUN
              value: "true"
            - name: REDEPLOY_ALLOWED_NAMESPACES
              value: "{','.join(allowed_namespaces)}"
            - name: REDEPLOY_EXCLUDED_NAMESPACES
              value: "kube-system,kube-public,kube-node-lease,neuvector"
            - name: K8S_TIMEOUT_SECONDS
              value: "5"
            - name: MAX_BODY_BYTES
              value: "1048576"
            - name: DEBUG
              value: "false"
          ports:
            - name: http
              containerPort: 8080
              protocol: TCP
          resources:
            requests:
              cpu: 10m
              memory: 32Mi
            limits:
              cpu: 100m
              memory: 128Mi
          livenessProbe:
            httpGet:
              path: /healthz
              port: http
            periodSeconds: 30
          readinessProbe:
            httpGet:
              path: /healthz
              port: http
            periodSeconds: 10
---
apiVersion: v1
kind: Service
metadata:
  name: destroyer
  namespace: {namespace}
spec:
  selector:
    app: destroyer
  ports:
    - name: http
      port: 8080
      targetPort: http
  type: ClusterIP
'''


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate a self-contained Kubernetes manifest for Destroyer"
    )
    parser.add_argument(
        "--namespace",
        "-n",
        default="default",
        help="Namespace for the deployment (default: default)",
    )
    parser.add_argument(
        "--enable-redeploy",
        action="store_true",
        help="Enable dry-run pod redeploy with an explicit namespace allowlist",
    )
    parser.add_argument(
        "--allowed-namespaces",
        default="",
        help="Comma-separated namespaces approved for redeploy",
    )
    parser.add_argument(
        "--output",
        "-o",
        default="destroyer-deployment.yaml",
        help="Output file (default: destroyer-deployment.yaml)",
    )
    args = parser.parse_args()

    try:
        allowed_namespaces = tuple(
            value.strip()
            for value in args.allowed_namespaces.split(",")
            if value.strip()
        )
        manifest = generate_yaml(
            args.namespace,
            enable_redeploy=args.enable_redeploy,
            allowed_namespaces=allowed_namespaces,
        )
    except ValueError as exc:
        parser.error(str(exc))

    try:
        Path(args.output).write_text(manifest, encoding="utf-8")
    except OSError as exc:
        raise SystemExit(f"Unable to write {args.output}: {exc}") from exc

    print(f"Wrote {args.output}")
    print(f"Apply with: kubectl apply -f {args.output}")
    print(
        f"Webhook URL: http://destroyer.{args.namespace}.svc.cluster.local:8080/"
    )


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as exc:
        print(exc, file=sys.stderr)
        sys.exit(1)
